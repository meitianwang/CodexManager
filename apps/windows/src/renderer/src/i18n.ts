const dictionaries: Record<AppLocaleID, Record<MessageKey, string>> = Object.fromEntries(
  appLocales.map((locale) => [locale, { ...enMessages, ...localizedOverrides[locale] }])
) as Record<AppLocaleID, Record<MessageKey, string>>;

export const messageKeys = Object.keys(enMessages) as MessageKey[];

export function createTranslator(locale: string | undefined): Translator {
  const messages = dictionaries[resolveAppLocale(locale ?? "en")];
  return (key, values) => formatMessage(messages[key] ?? enMessages[key], values);
}

export function languageNameKey(locale: AppLocaleID): MessageKey {
  switch (locale) {
    case "en":
      return "language.english";
    case "zh-Hans":
      return "language.simplified_chinese";
    case "zh-Hant":
      return "language.traditional_chinese";
    case "ja":
      return "language.japanese";
    case "ko":
      return "language.korean";
    case "fr":
      return "language.french";
    case "de":
      return "language.german";
    case "it":
      return "language.italian";
    case "es":
      return "language.spanish";
    case "ru":
      return "language.russian";
    case "nl":
      return "language.dutch";
  }
}

function formatMessage(message: string, values: Record<string, string | number> | undefined): string {
  if (!values) {
    return message;
  }
  return message.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match));
}
